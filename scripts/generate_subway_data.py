def main():
    os.makedirs(DATA_DIR, exist_ok=True)
    
    # 駅名ユニークマスタの構築
    all_stations_map = {}
    for line in SUBWAY_LINES:
        for st in line["stations"]:
            sname = st["name"]
            if sname not in all_stations_map:
                all_stations_map[sname] = {
                    "name": sname,
                    "lat": st["lat"],
                    "lon": st["lon"],
                    "lines": []
                }
            all_stations_map[sname]["lines"].append({
                "lineId": line["id"],
                "lineName": line["name"],
                "color": line["color"],
                "stationId": st["id"]
            })

    output_data = {
        "lines": SUBWAY_LINES,
        "stations": list(all_stations_map.values())
    }
    
    out_path = os.path.join(DATA_DIR, "subway_network.json")
    with open(out_path, "w", encoding="utf-8") as f:
        json.dump(output_data, f, ensure_ascii=False, indent=2)
        
    print(f"Subway network JSON generated: {out_path} ({len(all_stations_map)} unique stations, {len(SUBWAY_LINES)} lines)")

if __name__ == "__main__":
    main()
